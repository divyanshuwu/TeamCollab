-- Initial PostgreSQL schema for TeamCollab (Supabase).
-- Apply this file in the Supabase SQL Editor.

create table if not exists public.users (
  id integer generated by default as identity primary key,
  name varchar(100) not null,
  email varchar(255) not null unique,
  password_hash varchar(255) not null,
  auth_user_id varchar(36),
  is_active boolean not null default true,
  created_at timestamp without time zone default now()
);
alter table public.users add column if not exists auth_user_id varchar(36);
create unique index if not exists uq_users_auth_user_id on public.users (auth_user_id);

create table if not exists public.projects (
  id integer generated by default as identity primary key,
  name varchar(100) not null,
  description text,
  created_at timestamp without time zone default now(),
  owner_id integer not null references public.users(id)
);
create index if not exists ix_projects_owner on public.projects (owner_id);

create table if not exists public.project_members (
  id integer generated by default as identity primary key,
  project_id integer not null references public.projects(id),
  user_id integer not null references public.users(id),
  role varchar(20) not null default 'member',
  joined_at timestamp without time zone default now(),
  constraint uq_project_member unique (project_id, user_id)
);
create index if not exists ix_project_members_user on public.project_members (user_id);

create table if not exists public.tasks (
  id integer generated by default as identity primary key,
  title varchar(200) not null,
  description text,
  status varchar(20) not null default 'todo',
  priority varchar(20) not null default 'medium',
  project_id integer not null references public.projects(id),
  assigned_to integer references public.users(id),
  due_date timestamp without time zone,
  created_at timestamp without time zone default now()
);
create index if not exists ix_tasks_project_created on public.tasks (project_id, created_at desc);
